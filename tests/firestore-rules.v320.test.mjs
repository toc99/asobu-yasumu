import test,{after} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {initializeTestEnvironment,assertFails,assertSucceeds} from '@firebase/rules-unit-testing';
import {doc,collection,query,orderBy,limit,getDoc,getDocs,setDoc,updateDoc,deleteDoc,serverTimestamp,Timestamp} from 'firebase/firestore';
import {defaultConfig} from '../google-home-policy.js';
if(!process.env.FIRESTORE_EMULATOR_HOST){
 test('Google Home security integration requires Firestore emulator',{skip:true},()=>{});
}else{
 const env=await initializeTestEnvironment({projectId:'demo-asobu-v316',firestore:{host:'127.0.0.1',port:8080,rules:readFileSync(new URL('../firestore.rules',import.meta.url),'utf8')}});
 after(()=>env.cleanup());
 const h='v320-google-home';
 const parent=env.authenticatedContext('parent-user').firestore(),kid=env.authenticatedContext('kid-user').firestore();
 const bridge=env.authenticatedContext('speaker-user').firestore(),other=env.authenticatedContext('other-user').firestore();
 const d=(db,col,id)=>doc(db,'households',h,col,id);
 const config=(db)=>d(db,'googleHome','config');
 const setup={...defaultConfig(),enabled:true,bridgeUid:'speaker-user',speaker:'Living Room'};
 test('only parent can configure a dedicated speaker and it cannot modify family records',async()=>{
  await env.withSecurityRulesDisabled(async ctx=>{
   const db=ctx.firestore();
   await setDoc(d(db,'members','parent-user'),{role:'parent'});
   await setDoc(d(db,'members','kid-user'),{role:'kid'});
   await setDoc(d(db,'profiles','older'),{activeStart:0});
   await setDoc(d(db,'settings','main'),{});
   await setDoc(d(db,'pokemonInventory','older'),{version:1,owned:{},reserved:{},seen:{}});
   await setDoc(d(db,'rewards','a'),{claimedAt:Timestamp.now()});
   await setDoc(d(db,'activityRequests','a'),{reviewedAt:Timestamp.now()});
   await setDoc(d(db,'feedbackReports','private'),{description:'private'});
  });
  await assertFails(setDoc(config(kid),setup));
  await assertSucceeds(setDoc(config(parent),setup));
  await assertFails(setDoc(config(parent),{...setup,volume:100}));
  await assertSucceeds(getDoc(config(bridge)));
  await assertFails(getDoc(config(kid)));
  await assertFails(getDoc(config(other)));
  await assertSucceeds(getDoc(d(bridge,'profiles','older')));
  await assertSucceeds(getDoc(d(bridge,'settings','main')));
  await assertSucceeds(getDoc(d(bridge,'pokemonInventory','older')));
  await assertFails(getDocs(collection(bridge,'households',h,'profiles')));
  await assertFails(getDoc(d(bridge,'feedbackReports','private')));
  await assertFails(updateDoc(d(bridge,'profiles','older'),{activeStart:1}));
  await assertFails(updateDoc(d(bridge,'settings','main'),{videoLimitMinutes:1}));
  await assertFails(updateDoc(d(bridge,'pokemonInventory','older'),{version:2}));
  await assertFails(updateDoc(config(bridge),{enabled:false}));
  await assertSucceeds(getDocs(query(collection(bridge,'households',h,'rewards'),orderBy('claimedAt','desc'),limit(40))));
  await assertSucceeds(getDocs(query(collection(bridge,'households',h,'activityRequests'),orderBy('reviewedAt','desc'),limit(40))));
  await assertFails(getDocs(collection(bridge,'households',h,'rewards')));
  await assertFails(getDocs(query(collection(bridge,'households',h,'activityRequests'),limit(41))));
  const status={updatedAt:serverTimestamp(),bridgeUid:'speaker-user',state:'ready',device:'Living Room',history:[]};
  await assertSucceeds(setDoc(d(bridge,'googleHome','status'),status));
  await assertSucceeds(getDoc(d(parent,'googleHome','status')));
  await assertFails(setDoc(d(kid,'googleHome','status'),status));
  await assertSucceeds(updateDoc(config(parent),{command:{id:'abc',text:'テスト',at:serverTimestamp()}}));
  await assertSucceeds(updateDoc(config(parent),{volume:40}));
  const ids=Array.from({length:5},(_,i)=>i+'2345678-1234-1234-1234-123456789abc');
  await assertSucceeds(updateDoc(config(parent),{speakerIds:ids,routes:{bedtime:ids[1],manual:[ids[0],ids[2]].join(',')}}));
  await assertFails(updateDoc(config(kid),{speakerIds:ids}));
  await assertFails(updateDoc(config(bridge),{speakerIds:ids}));
  await assertFails(updateDoc(config(parent),{speakerIds:[ids[0],ids[0]]}));
  await assertFails(updateDoc(config(parent),{speakerIds:['invalid']}));
  await assertFails(updateDoc(config(parent),{routes:{unknown:ids[0]}}));
  await assertFails(updateDoc(config(parent),{routes:{bedtime:true}}));
  await assertFails(updateDoc(config(parent),{routes:{bedtime:'bad'}}));
  await assertFails(updateDoc(config(parent),{routes:{bedtime:ids[0]+'|'+ids[1]}}));
  await assertSucceeds(updateDoc(config(parent),{scanRequestedAt:serverTimestamp()}));
  const multiStatus={...status,updatedAt:serverTimestamp(),speakers:ids.map((id,i)=>({id,name:'Speaker '+i,online:i===0})),scannedAt:Date.now()};
  await assertSucceeds(setDoc(d(bridge,'googleHome','status'),multiStatus));
  await assertFails(setDoc(d(bridge,'googleHome','status'),{...multiStatus,speakers:[{id:ids[0],name:'x',online:true,host:'192.168.1.9'}]}));
  await assertFails(setDoc(d(parent,'googleHome','status'),multiStatus));
  await assertFails(getDoc(d(kid,'googleHome','status')));
  await assertSucceeds(updateDoc(config(parent),{routes:Object.fromEntries([...Object.keys(setup.types),'manual'].map(k=>[k,ids.join(',')]))}));

  // Same write shape as the actual settings form; preserve command and scan timestamps.
  const formData={...setup,speakerIds:[ids[0]],routes:{manual:ids[0]}};
  await assertSucceeds(setDoc(config(parent),formData,{mergeFields:Object.keys(formData)}));
  assert.deepEqual((await getDoc(config(parent))).data().routes,{manual:ids[0]});
  const cleared={...formData,routes:{}};
  await assertSucceeds(setDoc(config(parent),cleared,{mergeFields:Object.keys(cleared)}));
  const afterClear=(await getDoc(config(parent))).data();
  assert.deepEqual(afterClear.routes,{});
  assert.equal(afterClear.command.id,'abc');
  assert.ok(afterClear.scanRequestedAt);
  const q={version:1,waiting:2,active:1,types:['manual','gameDue'],activeTypes:['pokemon'],at:Date.now()};
  await assertSucceeds(setDoc(d(bridge,'googleHome','status'),{...multiStatus,updatedAt:serverTimestamp(),queue:q}));
  await assertFails(setDoc(d(bridge,'googleHome','status'),{...status,updatedAt:serverTimestamp(),queue:{...q,waiting:101}}));
  await assertFails(setDoc(d(bridge,'googleHome','status'),{...status,updatedAt:serverTimestamp(),queue:{...q,types:['private text']}}));
  await assertFails(setDoc(d(kid,'googleHome','status'),{...status,updatedAt:serverTimestamp(),queue:q}));
  const monitor={version:1,bridgeVersion:'v3.26.0',host:'home-server',platform:'linux',observedAt:Date.now(),uptimeSec:2400,cpuTempDeciC:520,memPercent:30,diskPercent:10,watchdog:'active',wifi:'connected',recoveryDay:'2026-11-26',attempts:1,successes:1,failures:0,events:[{at:Date.now(),kind:'success'}]};
  const monitorStatus={...status,monitor};
  // Old v3.26.0 falls back to legacy status on permission-denied.
  await assertFails(setDoc(d(bridge,'googleHome','status'),monitorStatus));
  await assertSucceeds(getDoc(d(parent,'googleHome','status')));
  await assertFails(getDoc(d(kid,'googleHome','status')));
  await assertFails(setDoc(d(parent,'googleHome','status'),monitorStatus));
  await assertFails(setDoc(d(other,'googleHome','status'),monitorStatus));
  for(const invalid of [{...monitor,ip:'192.168.1.24'},{...monitor,memPercent:101},{...monitor,observedAt:Date.now()+120000},{...monitor,events:[{at:Date.now(),kind:'raw journal'}]},{...monitor,events:Array(6).fill(monitor.events[0])},{...monitor,host:'secret text'}])await assertFails(setDoc(d(bridge,'googleHome','monitor'),{bridgeUid:'speaker-user',updatedAt:serverTimestamp(),monitor:invalid}));
  await assertSucceeds(setDoc(d(bridge,'googleHome','status'),status));
  // Production-sized status and monitor payloads are evaluated independently.
  const fullIds=Array.from({length:12},(_,i)=>i.toString(16).padStart(8,'0')+'-1234-1234-1234-123456789abc');
  const fullStatus={...status,speakers:fullIds.map(id=>({id,name:'Speaker '+id.slice(0,8),online:true})),scannedAt:Date.now(),queue:{version:1,waiting:10,active:4,types:Array(10).fill('manual'),activeTypes:Array(4).fill('pokemon'),at:Date.now()},history:Array(20).fill({type:'manual',result:'sent',at:Date.now()})};
  const fullMonitor={...monitor,bridgeVersion:'v3.26.1',observedAt:Date.now(),uptimeSec:2057,cpuTempDeciC:540,memPercent:8,diskPercent:9,events:['success','start','failure','blocked','recovered'].map(kind=>({at:Date.now(),kind}))};
  const telemetry=(db)=>d(db,'googleHome','monitor');
  const monitorDoc={bridgeUid:'speaker-user',updatedAt:serverTimestamp(),monitor:fullMonitor};
  console.log('Testing maximum 12-speaker status');
  await assertSucceeds(setDoc(d(bridge,'googleHome','status'),fullStatus));
  console.log('Testing maximum 5-event monitor');
  await assertSucceeds(setDoc(telemetry(bridge),monitorDoc));
  await assertSucceeds(getDoc(telemetry(parent)));
  await assertFails(getDoc(telemetry(kid)));
  await assertFails(getDoc(telemetry(other)));
  await assertFails(setDoc(telemetry(parent),monitorDoc));
  await assertFails(setDoc(telemetry(kid),monitorDoc));
  await assertFails(setDoc(telemetry(other),monitorDoc));
  await assertFails(setDoc(telemetry(bridge),{...monitorDoc,bridgeUid:'other-user'}));
  await assertFails(setDoc(telemetry(bridge),{...monitorDoc,monitor:{...fullMonitor,ip:'192.168.1.24'}}));
  await assertFails(setDoc(telemetry(bridge),{...monitorDoc,monitor:{...fullMonitor,events:Array(6).fill(fullMonitor.events[0])}}));
  await assertFails(setDoc(telemetry(bridge),{...monitorDoc,monitor:{...fullMonitor,events:[{at:Date.now(),kind:'raw journal'}]}}));
  await assertFails(setDoc(telemetry(bridge),{...monitorDoc,extra:true}));
  await assertSucceeds(setDoc(d(bridge,'googleHome','status'),status));
  const cmd=(db,i)=>d(db,'googleHomeCommands',ids[i]);
  const request=()=>({text:'音声通知テスト',at:serverTimestamp()});
  await assertSucceeds(setDoc(cmd(parent,0),request()));
  await assertSucceeds(setDoc(cmd(parent,1),request()));
  await assertFails(setDoc(cmd(parent,0),request()));
  await assertFails(setDoc(cmd(kid,2),request()));
  await assertFails(setDoc(cmd(bridge,2),request()));
  await assertFails(setDoc(cmd(parent,2),{...request(),extra:true}));
  await assertFails(setDoc(cmd(parent,2),{text:'x'.repeat(161),at:serverTimestamp()}));
  await assertFails(setDoc(cmd(parent,2),{text:'old',at:Timestamp.fromMillis(1000)}));
  const commands=db=>collection(db,'households',h,'googleHomeCommands');
  assert.equal((await assertSucceeds(getDocs(query(commands(bridge),orderBy('at','desc'),limit(40))))).size,2);
  await assertFails(getDocs(commands(bridge)));
  await assertFails(getDocs(query(commands(bridge),limit(41))));
  await assertFails(getDocs(query(commands(kid),limit(40))));
  await assertFails(getDoc(cmd(other,0)));
  await assertFails(deleteDoc(cmd(kid,0)));
  await assertSucceeds(deleteDoc(cmd(bridge,0)));
  await assertSucceeds(deleteDoc(cmd(parent,1)));
  await assertSucceeds(updateDoc(config(parent),{enabled:false,bridgeUid:''}));
  await assertFails(setDoc(cmd(parent,2),request()));
  await assertFails(getDocs(query(commands(bridge),limit(40))));
  await assertFails(getDoc(d(bridge,'profiles','older')));
  await assertFails(setDoc(d(bridge,'googleHome','status'),status));
  await assertFails(setDoc(telemetry(bridge),monitorDoc));
 });
}
